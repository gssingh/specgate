"""Stage 2 tests. All offline: a fake writer stands in for Claude."""

import json
from pathlib import Path
from types import SimpleNamespace

import pytest

from specgate.cli import EXIT_BAD_INPUT, EXIT_FAILED, EXIT_PASSED, main
from specgate.generate import (
    ClaudeTestWriter,
    Draft,
    GenerationError,
    Outcome,
    Target,
    generate_tests,
    write_outputs,
)
from specgate.prompts import build_user_message
from specgate.spec import load_specs

EXAMPLE = Path(__file__).parent.parent / "examples" / "identity_sync"
TARGET = Target(EXAMPLE / "identity_sync.py")
SYNC_001 = next(s for s in load_specs([EXAMPLE / "specs"]) if s.id == "SYNC-001")

GOOD = """
import pytest
from identity_sync import Action, ActionKind, HrRecord, HrStatus, plan_sync

@pytest.mark.spec("SYNC-001")
def test_new_hire():
    hr = [HrRecord("e100", HrStatus.ACTIVE, frozenset({"engineer"}))]
    assert plan_sync(hr, []) == [Action(ActionKind.CREATE, "e100", frozenset({"engineer"}))]
"""
WEAK = GOOD.replace("assert plan_sync(hr, []) == [", "assert plan_sync(hr, []) is not None  # [")
WRONG_ID = GOOD.replace('spec("SYNC-001")', 'spec("SYNC-999")')
WRONG_EXPECTATION = GOOD.replace("ActionKind.CREATE", "ActionKind.ENABLE")


class FakeTestWriter:
    """Returns canned drafts in order and records the feedback it was given."""

    def __init__(self, *replies: str | Exception):
        self.replies = list(replies)
        self.feedback: list[str | None] = []

    def write(self, scenario, target, feedback):
        self.feedback.append(feedback)
        reply = self.replies.pop(0)
        if isinstance(reply, Exception):
            raise reply
        return Draft(reply, assumptions="roles compared as sets")


def test_good_draft_is_kept_first_time():
    writer = FakeTestWriter(GOOD)

    [result] = generate_tests([SYNC_001], TARGET, writer)

    assert (result.outcome, result.attempts, result.problem) == (Outcome.KEPT, 1, "")
    assert writer.feedback == [None]


def test_weak_draft_gets_feedback_and_a_second_try():
    writer = FakeTestWriter(WEAK, GOOD)

    [result] = generate_tests([SYNC_001], TARGET, writer)

    assert (result.outcome, result.attempts) == (Outcome.KEPT, 2)
    assert "only checks the value is not None" in writer.feedback[1]


@pytest.mark.parametrize(
    ("draft", "problem"),
    [
        (WRONG_ID, "must claim exactly"),
        ("def test_x(:", "doesn't parse"),
        (
            'import pytest\n\n@pytest.mark.spec("SYNC-001")\ndef test_x():\n    pass\n',
            "no assertions",
        ),
        (GOOD + GOOD.replace("test_new_hire", "test_again"), "exactly one test"),
    ],
)
def test_malformed_drafts_are_rejected(draft, problem):
    [result] = generate_tests([SYNC_001], TARGET, FakeTestWriter(draft, draft))

    assert result.outcome is Outcome.REJECTED
    assert problem in result.problem


def test_draft_failing_against_the_code_needs_review():
    [result] = generate_tests(
        [SYNC_001], TARGET, FakeTestWriter(WRONG_EXPECTATION, WRONG_EXPECTATION)
    )

    assert result.outcome is Outcome.NEEDS_REVIEW
    assert "fails against the code" in result.problem
    assert "ENABLE" in result.problem  # pytest's assertion diff is passed along


def test_writer_error_uses_up_an_attempt():
    writer = FakeTestWriter(GenerationError("SYNC-001: model stopped with 'refusal'"), GOOD)

    [result] = generate_tests([SYNC_001], TARGET, writer)

    assert (result.outcome, result.attempts) == (Outcome.KEPT, 2)
    assert "refusal" in writer.feedback[1]


def test_outputs_keep_needs_review_out_of_pytests_way(tmp_path):
    kept = generate_tests([SYNC_001], TARGET, FakeTestWriter(GOOD))
    flagged = generate_tests(
        [SYNC_001], TARGET, FakeTestWriter(WRONG_EXPECTATION, WRONG_EXPECTATION)
    )
    rejected = generate_tests([SYNC_001], TARGET, FakeTestWriter(WRONG_ID, WRONG_ID))

    written = write_outputs(kept + flagged + rejected, tmp_path)

    assert [p.relative_to(tmp_path).as_posix() for p in written] == [
        "test_sync_001.py",
        "needs_review/sync_001_needs_review.py",
    ]
    text = written[0].read_text()
    assert text.startswith("# Generated by specgate from SYNC-001")
    assert "# Assumptions: roles compared as sets" in text


def test_user_message_carries_steps_source_and_feedback():
    message = build_user_message(SYNC_001, "identity_sync", "SOURCE", feedback="too weak")

    assert "Scenario SYNC-001: New hire gets an account" in message
    assert "When the sync runs" in message
    assert "imported as `identity_sync`" in message
    assert "SOURCE" in message
    assert message.endswith("too weak\nWrite a corrected test.")


class FakeClient:
    """Mimics client.beta.messages.create just enough for ClaudeTestWriter."""

    def __init__(self, stop_reason="end_turn"):
        self.stop_reason = stop_reason
        self.request = None
        self.beta = SimpleNamespace(messages=SimpleNamespace(create=self.create))

    def create(self, **request):
        self.request = request
        reply = json.dumps({"test_code": GOOD, "assumptions": ""})
        return SimpleNamespace(
            stop_reason=self.stop_reason, content=[SimpleNamespace(type="text", text=reply)]
        )


def test_claude_writer_requests_structured_output_and_parses_it():
    client = FakeClient()

    draft = ClaudeTestWriter(model="some-model", client=client).write(SYNC_001, TARGET, None)

    assert draft == Draft(GOOD, "")
    assert client.request["model"] == "some-model"
    assert client.request["output_config"]["format"]["type"] == "json_schema"
    assert "SYNC-001" in client.request["messages"][0]["content"]


def test_claude_writer_raises_when_model_does_not_finish():
    with pytest.raises(GenerationError, match="refusal"):
        ClaudeTestWriter(client=FakeClient("refusal")).write(SYNC_001, TARGET, None)


def run_generate(tmp_path, *extra):
    return main(
        [
            "generate",
            "--specs",
            str(EXAMPLE / "specs"),
            "--target",
            str(TARGET.path),
            "--out",
            str(tmp_path / "out"),
            "--only",
            "SYNC-001",
            *extra,
        ]
    )


def test_cli_end_to_end_with_fake_writer(tmp_path, monkeypatch, capsys):
    monkeypatch.setenv("ANTHROPIC_API_KEY", "not-used")
    monkeypatch.setattr("specgate.cli.ClaudeTestWriter", lambda model: FakeTestWriter(GOOD))

    exit_code = run_generate(tmp_path)

    out = capsys.readouterr().out
    assert exit_code == EXIT_PASSED
    assert "1/1 scenarios got a test" in out
    assert (tmp_path / "out" / "test_sync_001.py").exists()


def test_cli_fails_when_a_scenario_is_not_kept(tmp_path, monkeypatch, capsys):
    monkeypatch.setenv("ANTHROPIC_API_KEY", "not-used")
    monkeypatch.setattr("specgate.cli.ClaudeTestWriter", lambda model: FakeTestWriter(WEAK, WEAK))

    assert run_generate(tmp_path) == EXIT_FAILED
    assert "REJECTED" in capsys.readouterr().out


def test_cli_without_api_key_is_bad_input(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)  # so no real .env is picked up
    monkeypatch.delenv("ANTHROPIC_API_KEY", raising=False)
    monkeypatch.delenv("ANTHROPIC_AUTH_TOKEN", raising=False)

    assert run_generate(tmp_path) == EXIT_BAD_INPUT
    assert "ANTHROPIC_API_KEY" in capsys.readouterr().err


def test_cli_unknown_only_id_is_bad_input(tmp_path, capsys):
    assert run_generate(tmp_path, "--only", "SYNC-999") == EXIT_BAD_INPUT
    assert "SYNC-999" in capsys.readouterr().err
